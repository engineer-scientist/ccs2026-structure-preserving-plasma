import json, numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
R = json.load(open("/workspace/research/results/ct_results.json"))
fig, ax = plt.subplots(1, 2, figsize=(11, 4))
for k, lab in (("loop_uniform", "field loop, uniform flow"), ("loop_rotation", "field loop, rigid rotation")):
    h = R[k]["hist"]; t = np.array(h["t"])
    ax[0].semilogy(t, np.maximum(h["ct_divB"], 1e-17), label="CT (staggered) - " + lab)
    ax[0].semilogy(t, np.maximum(h["cc_divB"], 1e-17), "--", label="cell-centred baseline - " + lab)
st = np.loadtxt("/workspace/research/results/ct_stag_N128.dat")
ax[0].semilogy(st[:, 0], np.maximum(st[:, 1], 1e-17), "k.", ms=3, label="CT in PETSc DMSTAG+TS (C) - uniform flow")
ax[0].axhline(np.finfo(float).eps, color="gray", lw=0.8, ls=":"); ax[0].text(0.02, 3e-16, "machine eps", color="gray")
ax[0].set_xlabel("time"); ax[0].set_ylabel(r"max $|\nabla_h\cdot B|\,\Delta x/\max|B_0|$")
ax[0].set_title(r"Discrete $\nabla\cdot B$, field loop 128$^2$ (values $<10^{-17}$ clipped)", fontsize=9); ax[0].legend(fontsize=7); ax[0].set_ylim(1e-17, 1)
c = R["convergence"]; N = np.array([x["N"] for x in c]); e = np.array([x["err_ct"] for x in c]); ec = np.array([x["err_cc"] for x in c])
ax[1].loglog(N, e, "o-", label="CT"); ax[1].loglog(N, ec, "s--", label="cell-centred")
ax[1].loglog(N, e[0] * (N[0] / N) ** 2, "k:", label="slope 2")
p = np.log2(e[:-1] / e[1:])
ax[1].set_xlabel("N (cells per side)"); ax[1].set_ylabel("RMS error in B (t = 2)"); ax[1].legend()
ax[1].set_title("Smooth-field convergence, observed p = " + ", ".join(f"{x:.2f}" for x in p), fontsize=9)
plt.tight_layout(); plt.savefig("/workspace/research/results/figs/ct_divB_convergence.png", dpi=150)
print("orders", p, "max ct div", [max(R[k]["hist"]["ct_divB"]) for k in ("loop_uniform","loop_rotation")], "max cc", [max(R[k]["hist"]["cc_divB"]) for k in ("loop_uniform","loop_rotation")])
